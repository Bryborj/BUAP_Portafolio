def buildMap():
    global tile_map
    rows = len(map) * 8
    cols = len(map[0]) * 8

    for i in range(len(map) - 1):
        for j in range(len(map[0]) - 1):
            tile_id = map[i][j]
            data, palette = tg.getTile(tile_id)
            rgb_data = tg.converterRGB(data, palette)
            # print(rgb_data.shape) # Debug

            y = i * 8
            x = j * 8

            tile_map[y:y+8, x:x+8] = rgb_data

def run():
    def update_viewport():
        global POS_X, POS_Y

        viewport = tile_map[POS_Y:POS_Y + VIEWPORT_H, POS_X:POS_X + VIEWPORT_W]

        img.set_data(viewport)

        ax.set_title(f"Posición: ({POS_X}, {POS_Y}) | Tile: ({POS_X / 8}, {POS_Y / 8}) \n Viewport: ({VIEWPORT_W} x {VIEWPORT_H})")
        fig.canvas.draw_idle()

    def keyboard(event):
        global POS_X, POS_Y

        if event.key in ("left", "a"):
            POS_X = max(0, POS_X - 8)
        elif event.key in ("right", "d"):
            POS_X = min(MAX_X - VIEWPORT_W, POS_X + 8)
        elif event.key in ("up", "w"):
            POS_Y = max(0, POS_Y - 8)
        elif event.key in ("down", "s"):
            POS_Y = min(MAX_Y - VIEWPORT_H, POS_Y + 8)
        elif event.key == "escape":
            plt.close(fig)
            return
        update_viewport()

        
    buildMap()
    fig, ax = plt.subplots(figsize=(5, 5))
    viewport = tile_map[POS_Y:POS_Y + VIEWPORT_H, POS_X:POS_X + VIEWPORT_W]
    img = ax.imshow(viewport, interpolation='nearest', cmap='gray')
    ax.set_title(f"Posición: ({POS_X}, {POS_Y})")
    fig.canvas.mpl_connect("key_press_event", keyboard)
    #plt.show()

def showMap(): # Muestra el mapa de tiles de 40x40
    fig1, ax1 = plt.subplots()
    ax1.imshow(tile_map, interpolation='nearest', cmap='gray')
    ax1.set_title(f"Mapa de TILES de 40 x 40")

run()
