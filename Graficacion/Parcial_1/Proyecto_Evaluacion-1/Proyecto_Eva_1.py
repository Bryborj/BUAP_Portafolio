def buildMap():
    rows = len(map) * 8
    cols = len(map[0]) * 8

    for i in range(len(map) - 1):
        for j in range(len(map[0]) - 1):
            tile_id = map[i][j]
            data, palette = tg.getTile(tile_id)
            rgb_data = tg.converterRGB(data, palette)
            print(rgb_data.shape)

            y = i * 8
            x = j * 8

            tile_map[y:y+8, x:x+8] = rgb_data

    fig, ax = plt.subplots(figsize=(5, 5))
    ax.imshow(tile_map, interpolation='nearest')
    plt.show()
            
buildMap()

